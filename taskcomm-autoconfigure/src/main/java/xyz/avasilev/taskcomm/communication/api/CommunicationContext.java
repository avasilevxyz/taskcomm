package xyz.avasilev.taskcomm.communication.api;

import xyz.avasilev.taskcomm.execution.api.ExecutionRef;

/**
 * Контекст обработки — параметр каждого метода процессора коммуникаций, вызываемого движком.
 * Действителен только внутри вызова, в который передан. Свой у подсистемы коммуникаций: общего
 * типа с контекстом задач нет (docs/adr/0010-separate-engines.md).
 *
 * <p>Методы записи — обмена, ключей корреляции и дедупликации — пишут <b>немедленно, своей
 * короткой транзакцией</b>: падение после отправки не должно стереть то, что ушло наружу
 * (docs/adr/0055-communication-exchange-storage.md). В свою попытку они пишут и после потери
 * аренды. Остальные методы отвечают из памяти.
 */
public interface CommunicationContext {

    /**
     * Объявляет пропуск: обрабатывать не надо. Действует, только если метод затем вернулся
     * нормально; <b>исключение перебивает пропуск</b>. После вызова {@link #shouldStop()} отвечает
     * {@code true}.
     *
     * @param reason причина, обязательна; хранится в базе (docs/adr/0042-communication-statuses.md)
     */
    void skip(String reason);

    /**
     * Запрещает повтор: если метод затем бросит исключение, попытка станет последней, коммуникация —
     * {@code FAILED}. Без последующего исключения не делает ничего. Вызывать надо <b>до</b> броска
     * (docs/adr/0062-non-retryable-failure.md). Исключение после этого вызова размыкатель не считает.
     *
     * @param reason причина, обязательна
     */
    void doNotRetry(String reason);

    /**
     * Сигнал прекращения: {@code true} — пора остановиться. Поднимается при отмене коммуникации,
     * при потере аренды, после {@link #skip(String)} и после ключа дедупликации, оказавшегося
     * дубликатом. Поток процессора стартер не прерывает никогда.
     *
     * @return {@code true}, если работу надо прекратить
     */
    boolean shouldStop();

    /**
     * Ссылка на дело коммуникации — передайте её явно в метод создания из другого потока
     * (docs/adr/0056-execution-ref.md).
     *
     * @return ссылка на текущее дело
     */
    ExecutionRef executionRef();

    /**
     * Номер текущей попытки этой фазы с начала текущего цикла повторов, с единицы. Переход
     * к обработке ответа и ручной перезапуск начинают новый цикл.
     *
     * @return номер попытки, не меньше единицы
     */
    int attemptNumber();

    /**
     * Была ли у коммуникации более ранняя попытка той же фазы — за всю историю, включая время
     * до ручного перезапуска. Защиты от двойного выполнения не даёт: обработка обязана быть
     * идемпотентной в любом случае.
     *
     * @return {@code true}, если эту фазу уже пытались выполнить
     */
    boolean isRetry();

    /**
     * Записывает запрос в попытку. У исходящей — что ушло во внешнюю систему; пишите <b>до</b>
     * отправки. У входящей запрос записал стартер при приёме; повторная запись его заменяет.
     *
     * @param message запрос как по проводу
     */
    void recordRequest(ExchangeMessage message);

    /**
     * Записывает ответ в попытку. У исходящей — что ответила внешняя система; пишите сразу, как он
     * получен, <b>включая отказной</b>, и до броска исключения. Записанный ответ с отказным статусом
     * делает попытку неуспешной, даже если процессор вернулся нормально, и его же считает
     * размыкатель (docs/adr/0065-communication-circuit-breaker.md). Не записали — стартер ответа
     * не увидит, и {@code 503} пройдёт как успех.
     *
     * @param message ответ как по проводу
     */
    void recordResponse(ExchangeMessage message);

    /**
     * Регистрирует ключ корреляции от внешней стороны коммуникации. <b>На исходящей регистрация
     * включает ожидание асинхронного ответа</b>: после успешной отправки коммуникация станет
     * {@code AWAITING_RESPONSE}, а не {@code SUCCEEDED} (docs/adr/0104-wait-defined-by-correlation-key.md).
     * На входящей ожидания не включает.
     *
     * @param correlationId значение ключа — обычно номер, который вернула внешняя система
     */
    void registerCorrelationId(String correlationId);

    /**
     * Регистрирует ключ корреляции от явно названной системы. Ожидание включает, только если это
     * система самой исходящей; колбэк от другой системы становится отдельной входящей в этом деле
     * (docs/adr/0075-correlation-key-scoped-by-system.md).
     *
     * @param externalSystem система, от которой ждут колбэк
     * @param correlationId значение ключа
     */
    void registerCorrelationId(String externalSystem, String correlationId);

    /**
     * «Не ждать»: ключ корреляции нужен, а ответа не будет — успешная отправка даст
     * {@code SUCCEEDED}. Решение принимается по итогу метода; исключение перебивает ожидание.
     */
    void doNotAwaitResponse();

    /**
     * Регистрирует ключ дедупликации по всей истории и сразу отвечает, дубликат ли коммуникация
     * (docs/adr/0076-communication-deduplication.md). При дубликате {@link #shouldStop()} становится
     * {@code true}, нормальный возврат даёт {@code SKIPPED}, исключение перебивает пропуск.
     *
     * <p><b>То, что процессор сделал до вызова, не отменить</b>: ключ защищает только то, что после
     * него. Ключ, который можно посчитать заранее, задавайте при создании или в
     * {@link CommunicationProcessor#beforeProcess}.
     *
     * @param key значение ключа
     * @return {@code true}, если коммуникация — дубликат
     */
    boolean dedupKey(String key);

    /**
     * Регистрирует ключ дедупликации по последней успешной с этим предметом и сразу отвечает,
     * дубликат ли коммуникация. Последствия — как у {@link #dedupKey(String)}.
     *
     * @param subject предмет
     * @param key значение ключа
     * @return {@code true}, если коммуникация — дубликат
     */
    boolean dedupKey(String subject, String key);
}
